CREATE SEQUENCE IF NOT EXISTS quote_number_seq START 1;

CREATE OR REPLACE FUNCTION public.generate_quote_number()
RETURNS TEXT AS $$
BEGIN
  RETURN ''QT-'' || TO_CHAR(NOW(), ''YYYY'') || ''-'' || LPAD(nextval(''quote_number_seq'')::TEXT, 6, ''0'');
END;
$$ LANGUAGE plpgsql;

-- QUOTES
CREATE TABLE IF NOT EXISTS public.quotes (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  quote_number      TEXT NOT NULL UNIQUE DEFAULT public.generate_quote_number(),
  application_id    UUID NOT NULL REFERENCES public.applications(id) ON DELETE RESTRICT,
  customer_id       UUID NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
  vehicle_id        UUID NOT NULL REFERENCES public.vehicles(id) ON DELETE RESTRICT,
  agent_id          UUID REFERENCES public.agents(id),
  pricing_rule_id   UUID REFERENCES public.pricing_rules(id),
  -- Amounts (all in INR, stored as NUMERIC for precision)
  base_amount       NUMERIC(12,2) NOT NULL CHECK (base_amount >= 0),
  discount_pct      NUMERIC(5,2)  NOT NULL DEFAULT 0 CHECK (discount_pct >= 0 AND discount_pct <= 100),
  discount_amount   NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
  discount_type     TEXT NOT NULL DEFAULT ''percentage'' CHECK (discount_type IN (''percentage'', ''fixed'', ''combined'')),
  -- Additional charges (configurable, e.g., service fee)
  charges_amount    NUMERIC(12,2) NOT NULL DEFAULT 0,
  charges_label     TEXT,
  -- Computed total (must never be negative)
  payable_amount    NUMERIC(12,2) NOT NULL CHECK (payable_amount >= 0),
  -- Override tracking
  is_overridden     BOOLEAN NOT NULL DEFAULT false,
  override_reason   TEXT,
  overridden_by     UUID REFERENCES auth.users(id),
  overridden_at     TIMESTAMPTZ,
  -- Validity
  valid_until       DATE NOT NULL,
  status            TEXT NOT NULL DEFAULT ''active'' CHECK (status IN (''active'', ''expired'', ''superseded'', ''cancelled'')),
  -- IMPORTANT: This disclosure must always be shown to the customer
  disclosure        TEXT NOT NULL DEFAULT ''This is an internal quotation/estimate generated by the MotorSeva portal. It is NOT an official insurance quote from any insurer. The final premium, terms, and conditions will be determined by the actual insurer at the time of policy issuance through the authorized process.'',
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_quotes_application_id ON public.quotes(application_id);
CREATE INDEX idx_quotes_customer_id ON public.quotes(customer_id);
CREATE INDEX idx_quotes_status ON public.quotes(status);

CREATE TRIGGER quotes_updated_at BEFORE UPDATE ON public.quotes
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- QUOTE HISTORY (immutable -- never delete financial records)
CREATE TABLE IF NOT EXISTS public.quote_history (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  quote_id        UUID NOT NULL REFERENCES public.quotes(id) ON DELETE RESTRICT,
  -- Snapshot of values before change
  base_amount     NUMERIC(12,2) NOT NULL,
  discount_pct    NUMERIC(5,2)  NOT NULL,
  discount_amount NUMERIC(12,2) NOT NULL,
  payable_amount  NUMERIC(12,2) NOT NULL,
  charges_amount  NUMERIC(12,2) NOT NULL DEFAULT 0,
  change_reason   TEXT NOT NULL,
  changed_by      UUID NOT NULL REFERENCES auth.users(id),
  changed_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_quote_history_quote_id ON public.quote_history(quote_id);
